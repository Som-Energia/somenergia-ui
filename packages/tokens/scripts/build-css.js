// Writes dist/tokens.css from src/index.js and dist/fonts.css with the
// Outfit variable font files copied from @fontsource-variable/outfit,
// so projects don't depend on Google Fonts.

import { copyFileSync, mkdirSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import tokensToCss from "../src/css.js"
import tokens from "../src/index.js"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const dist = resolve(root, "dist")

mkdirSync(resolve(dist, "fonts"), { recursive: true })
writeFileSync(resolve(dist, "tokens.css"), tokensToCss(tokens))

// Subsets and unicode ranges from @fontsource-variable/outfit/index.css
const outfitSubsets = {
  "latin-ext":
    "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
  latin:
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
}

const outfit = dirname(
  createRequire(import.meta.url).resolve(
    "@fontsource-variable/outfit/package.json",
  ),
)
copyFileSync(resolve(outfit, "LICENSE"), resolve(dist, "fonts/OUTFIT-LICENSE"))

const fontFaces = Object.entries(outfitSubsets).map(([subset, range]) => {
  const file = `outfit-${subset}-wght-normal.woff2`
  copyFileSync(resolve(outfit, "files", file), resolve(dist, "fonts", file))
  return `@font-face {
  font-family: Outfit;
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  src: url(./fonts/${file}) format("woff2-variations");
  unicode-range: ${range};
}`
})

writeFileSync(
  resolve(dist, "fonts.css"),
  `/* Outfit variable font (OFL-1.1, see fonts/OUTFIT-LICENSE). Generated by scripts/build-css.js. */\n${fontFaces.join("\n\n")}\n`,
)

console.log(`Generated tokens.css and fonts.css in ${dist}`)
